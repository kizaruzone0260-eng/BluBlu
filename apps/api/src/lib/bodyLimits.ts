/**
 * Пределы размера тела запроса (задача 2026-10-27, часть A).
 *
 * Зачем это вынесено в файл, а не написано числом в `app.ts`. До этого изменения предел тела
 * вообще не был назван в коде: действовал молчаливый дефолт Fastify (1 МБ), и из исходников было
 * не видно ни самого числа, ни того, что оно строже некоторых схем. Консультация по Zod
 * GHSA-mrhx-c7xc-m3w5 («Zod исчерпывает память на oversized constrained collections») лечится
 * версией пакета, но класс задачи — «публичный вход обязан иметь измеримый потолок ДО разбора» —
 * остаётся: схема с `.max(20000)` не помогает, если транспорт уже впустил тело произвольного
 * размера, и наоборот.
 *
 * Что здесь сознательно НЕ ограничено:
 *  • загрузки файлов — это `@fastify/multipart` со своими `fileSize`/`files` (см. `app.ts`);
 *  • кадры доски по WebSocket — там потолок на уровне протокола (`maxPayload: 256 КБ`).
 */

/**
 * Общий предел JSON-тела — 1 МБ. Ровно то, что Fastify применял и раньше по умолчанию, поэтому
 * поведение существующих маршрутов не меняется: предел просто назван, зафиксирован тестом и не
 * может «поплыть» вместе с версией фреймворка.
 *
 * Он строже, чем потолки некоторых схем (например, конспект на 800 000 символов в `notes.ts`):
 * для кириллицы 800 000 символов — это ~1,6 МБ UTF-8, то есть транспорт отрежет такой текст
 * раньше схемы. Легитимного конспекта такого объёма не существует (это ~400 страниц), поэтому
 * предел оставлен прежним, а не поднят под схему.
 */
export const JSON_BODY_LIMIT = 1_048_576;

/**
 * Исключение: публикация страницы доски картинкой (POST /api/lessons/:id/board/publish).
 *
 * Схема этого маршрута с самого начала обещала принять до 12 000 000 символов base64 (~8 МБ
 * декодированного PNG/SVG), а транспорт молча резал тело на 1 МБ — доска с плотным рисунком или
 * вложенным изображением не публиковалась вовсе, и учитель видел голый 413 без объяснения.
 * Предел поднят ровно до уже объявленного контракта (+ запас на JSON-обёртку), а не «на глаз»:
 * маршрут доступен только аутентифицированному учителю-владельцу класса, а сопоставимый по
 * объёму вход в продукте уже есть и он шире — загрузка материала до `MAX_FILE_MB` (100 МБ).
 */
export const BOARD_PUBLISH_BODY_LIMIT = 12_600_000;
