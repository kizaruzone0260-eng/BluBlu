import { env } from '../env.js';
import { effectiveIpFailMax } from './prodConfig.js';
import { throttleCheck, throttleRecordAttempt, throttleReset } from './throttle.js';

/**
 * Единый учёт ПРОМАХОВ по токену приглашения (задача 2026-10-24).
 *
 * Почему это отдельный модуль, а не три строки в каждом маршруте. Публичных точек у
 * приглашения три — `preview`, `register` и `join`, — и все три отвечают на один и тот же
 * вопрос «что за токен мне прислали». Когда счётчик вело только одно из них, защита превращалась
 * в обход: промах, засчитанный в `preview`, стоил адреса ничего в `register`, и перебор
 * спокойно переезжал на маршрут, который не считает. Хелпер не даёт этой вилке появиться снова:
 * ключ, потолок и правила у всех трёх одни, и отличаются только тексты ответов.
 *
 * Что считается промахом, а что нет — часть контракта, а не деталь реализации:
 *  • промах: токен плохой ЛЮБОЙ причиной — не найден по хешу, истёк, отозван, уже использован.
 *    Все четыре состояния маршрут и называет отдельно (ученику нужна причина), но для счётчика
 *    они равны: стук в закрытую дверь — это тоже стук;
 *  • НЕ промах: кривые поля формы, слабый пароль, отказ по уже занятой почте, ошибка аутентификации.
 *    Там токен прошёл (или до него вообще не дошло), а такие отказы честный человек делает
 *    постоянно; считать их — значит закрывать школу за опечатку в фамилии.
 *
 * Успешная проверка токена счётчик обнуляет (`throttleReset`) — ровно как на входе по коду
 * класса: 30 учеников с одного адреса не должны платить за соседа, который пять раз промахнулся.
 *
 * Потолок берётся из `effectiveIpFailMax` при КАЖДОМ вызове, а не один раз при регистрации
 * маршрутов: в проде это 20 в минуту и блок на 15 минут после них, а в тестовой среде — 500,
 * потому что тесты и e2e намеренно производят промахи пачками с одного `127.0.0.1`.
 */
export const INVITE_JUNK_PREFIX = 'ivj:';

/** Ключ счётчика: адрес + признак «промах по токену». Один и тот же на всех трёх маршрутах. */
export function inviteJunkKey(ip: string): string {
  return `${INVITE_JUNK_PREFIX}${ip}`;
}

/** Актуальный потолок на адрес. Читается здесь, а не захватывается при старте приложения. */
export function inviteJunkMax(): number {
  return effectiveIpFailMax(env.NODE_ENV, env.RATE_IP_FAIL_MAX);
}

/** Открыт ли адрес. Делать это надо ДО любого обращения к базе. */
export function inviteJunkGate(ip: string): { allowed: boolean; retryAfterSec: number } {
  return throttleCheck(inviteJunkKey(ip));
}

/** Плохой токен: один засчитанный промах. */
export function noteInviteTokenMiss(ip: string): void {
  throttleRecordAttempt(inviteJunkKey(ip), Date.now(), inviteJunkMax());
}

/** Хороший токен: счётчик промахов адреса обнуляется. */
export function noteInviteTokenHit(ip: string): void {
  throttleReset(inviteJunkKey(ip));
}
