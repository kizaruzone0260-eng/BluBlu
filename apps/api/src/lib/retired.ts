/**
 * Ответ выведенного из продукта способа приёма в класс (2026-10-27).
 *
 * Один на все четыре оставленных «мертвых» маршрута — ровно по той же причине, по которой все
 * ошибки идут через `errorBody`: у маршрута, который больше ничего не умеет, не должно быть
 * собственной копии тела ответа, иначе однажды они разойдутся то по коду, то по статусу, и
 * интерфейс начнёт переводить одно из четырёх.
 *
 * 410 Gone, а не 404: путь существовал и вёл в класс, и честный ответ на него — «этого больше
 * нет» с переводимой причиной. Прежняя сборка SPA (её держат браузеры школы), закладочка
 * `/register` и скрипты владельца приходят сюда сами; молчаливый 404 или «Route not found» от
 * фреймворка человек прочитал бы как сломанное приложение.
 *
 * `reqId` в ответе остаётся. В интерфейсе он больше не показывается (`AuthError`), но по нему
 * строка ищется в access-логе — именно так владелец узнаёт, сколько ещё клиентов стучатся по
 * старому адресу и можно ли вырезать маршрут совсем.
 *
 * Ничего, кроме ответа, эти маршруты не делают: функции, умевшие проверять, расходовать или
 * выпускать восьмизначный код класса (`registerStudentByCode`, `peekInviteCode`,
 * `redeemInviteCode`, `createInviteCode`, `listInviteCodes`), из кодовой базы удалены, так что
 * `invite_codes.kind = 'code'` больше не читается нигде как право на вход. Исторические строки
 * при этом остаются в базе: их не удаляли — удаление не требовалось и стёрло бы историю.
 */
import type { FastifyReply, FastifyRequest } from 'fastify';
import { errorBody } from './requestId.js';

export function retiredEnrollment(req: FastifyRequest, reply: FastifyReply) {
  return reply.code(410).send(errorBody(req.id, 'enrollmentRetired'));
}
