/**
 * Ограничение одновременных тяжёлых загрузок (2026-10-28, аудит SEC-10, CWE-770/CWE-400).
 *
 * Что именно тут дорого. Маршруты вложений (`routes/posts.ts`) читают multipart целиком в память
 * (`part.toBuffer()`) и держат все буферы до конца записи в хранилище, а потолок на запрос —
 * `MAX_FILE_MB × 4 файла` (100 MB по умолчанию, 50 на Render). Один запрос поэтому легок, а N
 * одновременных — нет: лимит размера считается на один запрос, и он ничего не говорит о том,
 * сколько запросов сервер держит одновременно. Именно это и превращает лимит в фикцию: учителю с
 * сессией хватает нескольких параллельных загрузок, чтобы положить контейнер.
 *
 * Почему счёт, а не очередь. Очередь спрятала бы проблему за растущим числом висящих запросов:
 * каждый ждущий тоже держит раскрытый multipart и соединение, то есть память никуда не делась, а
 * стала невидимой. Четвертый запрос получает 429 с `Retry-After` — честный «потом», который
 * клиент умеет показать словами, и который ничего не держит.
 *
 * Почему модуль, а не `@fastify/rate-limit`. У лимитов по запросу есть потолок `RATE_*` и он
 * считает обращения, а не занятые байты; нам нужен именно счётчик одновременно активных
 * загрузок, и он один на процесс — как `lib/throttle.ts`, но по другой причине (не про перебор,
 * а про память).
 *
 * Тестуемость: `tryAcquireUploadSlot`/`releaseUploadSlot` экспортированы напрямую, потому что
 * доказательство «четвёртый не проходит» требует занять слоты из теста; без этого интеграционный
 * прогон зависел бы от скорости машины.
 */
import { env } from '../env.js';

let limit = Math.max(1, Math.floor(env.MAX_CONCURRENT_UPLOADS || 1));
let active = 0;

/** Взять слот. false — мест нет, грузить сейчас нельзя. */
export function tryAcquireUploadSlot(): boolean {
  if (active >= limit) return false;
  active++;
  return true;
}

/** Отдать слот. Парный вызов обязателен: утечка здесь означала бы вечный 429. */
export function releaseUploadSlot(): void {
  active = Math.max(0, active - 1);
}

/** Сколько держится сейчас — для теста и для диагностического ответа. */
export function activeUploads(): number { return active; }

/** Тестовый хук: временно другой потолок (production значение — из env, см. `env.ts`). */
export function setUploadSlotLimit(n: number): number {
  const previous = limit;
  limit = Math.max(1, Math.floor(n) || 1);
  return previous;
}
