/**
 * Кнопка панели формата не имеет права снимать фокус с редактора.
 *
 * Причина (2026-10-17, красные `zz24:91` и `zz24:143` в прогоне 39034112298). Браузер отдаёт
 * фокус кнопке ещё на `mousedown`, то есть ДО того, как отработает `onClick` с командой. Клик по
 * **Жирный** значит: редактор теряет фокус → наш `blur` отдаёт значение родителю → клик командой
 * возвращает фокус → первый же следующий символ попадает в окно между этими двумя состояниями, и
 * ProseMirror теряет его на прежнем месте, а позже вставляет в конец. Ровно это и показывают
 * замеры: `…0123456789[ч]арли…3210[e]cho…` → `…0123456789арли…3210ho…юю[ч]`, то есть потерян
 * ПЕРВЫЙ символ после кнопки формата и он же всплывает в хвосте.
 *
 * `preventDefault` на `mousedown` — штатное решение (так же сделана панель в примерах TipTap):
 * фокус никуда не уходит, `blur` не срабатывает посреди набора, команда из `onClick` работает по
 * живому выделению. `tabIndex` не трогается: кнопка остаётся в порядке обхода, с клавиатуры
 * `Enter`/`Space` по-прежнему нажимают её, а `onClick` там и остаётся — меняем только то, что
 * делает мышь с фокусом.
 */
export function keepFocus(e: { preventDefault: () => void }): void {
  e.preventDefault();
}
